//! Embeds the console (`ui/`) into the binary: `$OUT_DIR/ui_files.rs` lists every file the
//! `ui` component serves, as `(path, include_bytes!(...))`. Left out: dot files, `*.md`, and
//! the top-level `tests/` and `fixtures/` (development material the console does not load).
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const SKIP_TOP: [&str; 2] = ["tests", "fixtures"];

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) -> std::io::Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)?.collect::<Result<_, _>>()?;
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let name = e.file_name().to_string_lossy().into_owned();
        if name.starts_with('.') || name.ends_with(".md") {
            continue;
        }
        let path = e.path();
        if e.file_type()?.is_dir() {
            if dir == root && SKIP_TOP.contains(&name.as_str()) {
                continue;
            }
            collect(root, &path, out)?;
        } else if let Ok(rel) = path.strip_prefix(root) {
            let rel: Vec<String> = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect();
            out.push((rel.join("/"), path.canonicalize()?));
        }
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let ui = manifest.join("../../ui");
    println!("cargo:rerun-if-changed={}", ui.display());
    println!("cargo:rerun-if-changed=build.rs");
    let mut files = Vec::new();
    if ui.is_dir() {
        collect(&ui, &ui, &mut files)?;
    }
    let mut src = String::from(
        "/// Every embedded console file: (path relative to `ui/`, bytes). Generated by build.rs.\npub static FILES: &[(&str, &[u8])] = &[\n",
    );
    for (rel, abs) in &files {
        let abs = abs.to_string_lossy();
        writeln!(src, "    ({rel:?}, include_bytes!({abs:?})),")?;
    }
    src.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR")?).join("ui_files.rs");
    std::fs::write(out, src)?;
    Ok(())
}
