//! The `charters.agentsc.io` CustomResourceDefinition (design §4, §8.4, §13), generated from the
//! Rust types: `agentsc charter schema --crd` prints it, and a test keeps
//! `deploy/crds/charters.agentsc.io.yaml` in sync.
//!
//! Kubernetes wants a *structural* schema (every node typed, no `$ref`, no `anyOf` that changes
//! the structure, no `additionalProperties: false`, no `uniqueItems`, defaults that are its
//! business). [`structural`] turns the charter's JSON Schema into one: references are inlined,
//! `Option<T>` becomes `nullable: true`, and a subtree JSON Schema features cannot be expressed in
//! falls back to `x-kubernetes-preserve-unknown-fields: true`.
//!
//! **No pruning** (design §13). Every object node carries `x-kubernetes-preserve-unknown-fields:
//! true`, so the API server never drops a field it does not know. Pruning happens before
//! admission, and the validating webhook (the charter validator, which rejects unknown fields)
//! must see exactly what the user wrote, not a silently trimmed copy. The one exception is the
//! root `metadata`, where Kubernetes allows nothing but restrictions on `name` and
//! `generateName` (`ObjectMeta` is the API server's own business). The full rules (unknown
//! fields, uniqueness, cross-field checks) stay with the charter validator behind the validating
//! webhook.

use serde_json::{Map, Value, json};

use crate::resource::CharterSpec;
use crate::{API_VERSION, KIND};

pub const GROUP: &str = "agentsc.io";
pub const VERSION: &str = "v1alpha1";
pub const PLURAL: &str = "charters";
/// `metadata.name` of the CRD.
pub const CRD_NAME: &str = "charters.agentsc.io";

const PRESERVE: &str = "x-kubernetes-preserve-unknown-fields";
/// Deep enough for any charter type; a deeper (recursive) schema is cut off as "any".
const MAX_DEPTH: usize = 32;

/// The CustomResourceDefinition as a JSON value.
pub fn custom_resource_definition() -> Value {
    debug_assert_eq!(API_VERSION, format!("{GROUP}/{VERSION}"));
    let spec_schema = serde_json::to_value(schemars::schema_for!(CharterSpec)).unwrap_or(json!({}));
    let mut spec = structural(&spec_schema);
    if let Value::Object(m) = &mut spec {
        m.insert(
            "description".into(),
            Value::String(
                "The charter of one service (CONTRACT.md §3) without apiVersion and kind. \
                 metadata.name must equal service.name; service.namespace defaults to \
                 metadata.namespace."
                    .into(),
            ),
        );
    }
    json!({
        "apiVersion": "apiextensions.k8s.io/v1",
        "kind": "CustomResourceDefinition",
        "metadata": {
            "name": CRD_NAME,
            "labels": {"app.kubernetes.io/part-of": "agentsc"},
        },
        "spec": {
            "group": GROUP,
            "names": {
                "kind": KIND,
                "listKind": format!("{KIND}List"),
                "plural": PLURAL,
                "singular": "charter",
                "categories": ["agentsc"],
            },
            "scope": "Namespaced",
            "versions": [{
                "name": VERSION,
                "served": true,
                "storage": true,
                "subresources": {"status": {}},
                "additionalPrinterColumns": [
                    {"name": "Service", "type": "string", "jsonPath": ".spec.service.name"},
                    {"name": "Version", "type": "string", "jsonPath": ".status.appliedVersion"},
                    {"name": "Valid", "type": "string", "jsonPath": ".status.conditions[?(@.type==\"Valid\")].status"},
                    {"name": "Synced", "type": "string", "jsonPath": ".status.conditions[?(@.type==\"Synced\")].status"},
                    {"name": "Age", "type": "date", "jsonPath": ".metadata.creationTimestamp"},
                ],
                "schema": {"openAPIV3Schema": {
                    "type": "object",
                    "description": "Charter: the agents and policy of one service, applied by its agentsc sidecars.",
                    PRESERVE: true,
                    "properties": {
                        "apiVersion": {"type": "string"},
                        "kind": {"type": "string"},
                        // only name/generateName restrictions are allowed here: no PRESERVE
                        "metadata": {"type": "object"},
                        "spec": spec,
                        "status": status_schema(),
                    },
                    "required": ["spec"],
                }},
            }],
        },
    })
}

/// The CRD as YAML, with a header saying where it comes from (the content of
/// `deploy/crds/charters.agentsc.io.yaml`).
pub fn crd_yaml() -> String {
    let body = serde_yaml_ng::to_string(&custom_resource_definition())
        .unwrap_or_else(|e| format!("# cannot serialize the CRD: {e}\n"));
    format!(
        "# Generated by `agentsc charter schema --crd` from the Rust charter types; do not edit.\n\
         # A test keeps this file in sync: cargo run -q -p agentsc-cli -- charter schema --crd > deploy/crds/{CRD_NAME}.yaml\n\
         {body}"
    )
}

/// `status` (design §8.4), written by embassy only: `observedGeneration`, `appliedVersion`,
/// conditions `Valid` and `Synced`, and `memory` / `proposals`, whose shape is the store's.
fn status_schema() -> Value {
    json!({
        "type": "object",
        "description": "Written by embassy only.",
        PRESERVE: true,
        "properties": {
            "observedGeneration": {"type": "integer", "format": "int64"},
            "appliedVersion": {"type": "string", "description": "The charter version embassy applied from this resource."},
            "conditions": {
                "type": "array",
                "x-kubernetes-list-type": "map",
                "x-kubernetes-list-map-keys": ["type"],
                "items": {
                    "type": "object",
                    PRESERVE: true,
                    "required": ["type", "status"],
                    "properties": {
                        "type": {"type": "string", "description": "Valid or Synced."},
                        "status": {"type": "string", "enum": ["True", "False", "Unknown"]},
                        "observedGeneration": {"type": "integer", "format": "int64"},
                        "lastTransitionTime": {"type": "string", "format": "date-time"},
                        "reason": {"type": "string"},
                        "message": {"type": "string"},
                    },
                },
            },
            "memory": {
                "type": "object",
                "description": "The service's memory (version and notes per agent).",
                PRESERVE: true,
            },
            "proposals": {
                "description": "Learning proposals of the service's agents.",
                PRESERVE: true,
            },
        },
    })
}

/// Turn a JSON Schema (as schemars writes it, with `$defs`) into a Kubernetes structural schema.
pub fn structural(schema: &Value) -> Value {
    let empty = Map::new();
    let defs = schema
        .get("$defs")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    convert(schema, defs, 0)
}

/// Any value at all, kept as written (with a description when there is one).
fn any(description: Option<&Value>) -> Value {
    let mut m = Map::new();
    if let Some(d) = description {
        m.insert("description".into(), d.clone());
    }
    m.insert(PRESERVE.into(), Value::Bool(true));
    Value::Object(m)
}

fn is_null_schema(v: &Value) -> bool {
    v.get("type").and_then(Value::as_str) == Some("null")
        || v.get("const").is_some_and(Value::is_null)
}

fn convert(node: &Value, defs: &Map<String, Value>, depth: usize) -> Value {
    let Some(obj) = node.as_object() else {
        return any(None); // `true` (any value); `false` never appears in a charter type
    };
    let description = obj.get("description");
    if depth > MAX_DEPTH {
        return any(description);
    }

    // `$ref`: the definition, with this node's own keywords (description, default) on top.
    if let Some(r) = obj.get("$ref") {
        let def = r
            .as_str()
            .and_then(|r| r.strip_prefix("#/$defs/"))
            .and_then(|name| defs.get(name))
            .and_then(Value::as_object);
        let Some(def) = def else {
            return any(description);
        };
        let mut merged = def.clone();
        for (k, v) in obj.iter().filter(|(k, _)| k.as_str() != "$ref") {
            merged.insert(k.clone(), v.clone());
        }
        return convert(&Value::Object(merged), defs, depth + 1);
    }

    // `anyOf` / `oneOf`: `Option<T>` (T or null) is T made nullable; a choice of string
    // constants is an enum; anything else cannot be structural.
    for key in ["anyOf", "oneOf"] {
        let Some(branches) = obj.get(key) else {
            continue;
        };
        let branches = branches.as_array().map(Vec::as_slice).unwrap_or_default();
        let nullable = branches.iter().any(is_null_schema);
        let rest: Vec<&Value> = branches.iter().filter(|b| !is_null_schema(b)).collect();
        let mut out = if let [one] = rest.as_slice() {
            let mut merged = one.as_object().cloned().unwrap_or_default();
            for (k, v) in obj.iter().filter(|(k, _)| k.as_str() != key) {
                merged.insert(k.clone(), v.clone());
            }
            convert(&Value::Object(merged), defs, depth + 1)
        } else if let Some(values) = string_constants(&rest) {
            let mut m = Map::new();
            m.insert("type".into(), "string".into());
            if let Some(d) = description {
                m.insert("description".into(), d.clone());
            }
            m.insert("enum".into(), Value::Array(values));
            Value::Object(m)
        } else {
            return any(description);
        };
        if nullable && let Value::Object(m) = &mut out {
            m.insert("nullable".into(), Value::Bool(true));
        }
        return out;
    }

    let mut out = Map::new();
    // `type`: one name; `[T, "null"]` is T made nullable; several types cannot be structural.
    let mut nullable = false;
    match obj.get("type") {
        Some(Value::String(t)) if t != "null" => {
            out.insert("type".into(), Value::String(t.clone()));
        }
        Some(Value::Array(types)) => {
            nullable = types.iter().any(|t| t == "null");
            let rest: Vec<&Value> = types.iter().filter(|t| *t != "null").collect();
            match rest.as_slice() {
                [t] => {
                    out.insert("type".into(), (*t).clone());
                }
                _ => return any(description),
            }
        }
        _ => {}
    }
    if let Some(d) = description {
        out.insert("description".into(), d.clone());
    }
    if nullable || obj.get("nullable") == Some(&Value::Bool(true)) {
        out.insert("nullable".into(), Value::Bool(true));
    }
    if let Some(c) = obj.get("const") {
        out.insert("enum".into(), Value::Array(vec![c.clone()]));
    }
    for key in [
        "enum",
        "minimum",
        "maximum",
        "minLength",
        "maxLength",
        "pattern",
        "minItems",
        "maxItems",
    ] {
        if let Some(v) = obj.get(key) {
            out.insert(key.into(), v.clone());
        }
    }
    if let Some(items) = obj.get("items") {
        if items.is_object() || items.is_boolean() {
            out.insert("items".into(), convert(items, defs, depth + 1));
        } else {
            return any(description);
        }
    }
    let props = obj.get("properties").and_then(Value::as_object);
    if let Some(props) = props {
        let converted: Map<String, Value> = props
            .iter()
            .map(|(k, v)| (k.clone(), convert(v, defs, depth + 1)))
            .collect();
        out.insert("properties".into(), Value::Object(converted));
    }
    // A map (a schema for every value, no `properties`) keeps that schema. `false` (a closed
    // object), `true`, and a schema next to `properties` (which cannot be structural) are not
    // for the API server: unknown fields are the validator's to reject, never pruned.
    if props.is_none()
        && let Some(schema) = obj.get("additionalProperties").filter(|s| s.is_object())
    {
        out.insert(
            "additionalProperties".into(),
            convert(schema, defs, depth + 1),
        );
    }
    if let Some(Value::Array(req)) = obj.get("required") {
        out.insert("required".into(), Value::Array(req.clone()));
    }
    // Every object keeps the fields it does not declare (see the module docs): the API server
    // never prunes, so the validating webhook sees the resource exactly as written.
    if out.get("type").and_then(Value::as_str) == Some("object")
        || obj.get("additionalProperties") == Some(&Value::Bool(true))
    {
        out.insert(PRESERVE.into(), Value::Bool(true));
    }
    if !out.contains_key("type") && !out.contains_key(PRESERVE) {
        // untyped (e.g. a free-form JSON value such as a tool's `parameters`)
        return any(description);
    }
    if out.contains_key(PRESERVE) && out.get("type").is_some_and(|t| t != "object") {
        out.remove(PRESERVE);
    }
    Value::Object(out)
}

/// `[{const: "a"}, {const: "b"}, {enum: ["c"]}]` → `["a", "b", "c"]`.
fn string_constants(branches: &[&Value]) -> Option<Vec<Value>> {
    let mut values = Vec::new();
    for b in branches {
        if let Some(c) = b.get("const") {
            values.push(c.clone());
        } else if let Some(Value::Array(e)) = b.get("enum") {
            values.extend(e.iter().cloned());
        } else {
            return None;
        }
    }
    (!values.is_empty() && values.iter().all(Value::is_string)).then_some(values)
}
