#!/usr/bin/env bash
# Generate the Compose stack's .env (docs/design/agent-platform.md §14) with `embassy token create`:
# an admin API token and one join token per service, each with its SHA-256 (all that embassy's
# ControlPlaneConfig holds) and, for join tokens, its expiry. Written once with mode 0600; an
# existing file is kept, so tokens stay valid across `make compose-up` runs.
#
#   deploy/compose/gen-env.sh [path]          default path: deploy/compose/.env
#
# EMBASSY is the embassy command (default: the image built for Compose, `docker run --rm
# attache/embassy:dev`; a host build works too: EMBASSY=./target/debug/embassy).
# Variables written:
#   ATTACHE_NAMESPACE
#   ATTACHE_ADMIN_TOKEN, ATTACHE_ADMIN_TOKEN_SHA256
#   ATTACHE_JOIN_TOKEN_<SVC>, ATTACHE_JOIN_TOKEN_<SVC>_SHA256, ATTACHE_JOIN_TOKEN_<SVC>_EXPIRES_AT
set -euo pipefail

ENV_FILE=${1:-$(dirname "$0")/.env}
EMBASSY=${EMBASSY:-docker run --rm attache/embassy:dev}
NAMESPACE=${ATTACHE_NAMESPACE:-attache-demo}
SERVICES=${SERVICES:-orders inventory}
JOIN_TOKEN_TTL=${JOIN_TOKEN_TTL:-8760h}

if [[ -s $ENV_FILE ]]; then
  echo "keeping $ENV_FILE (delete it to create new tokens)"
  exit 0
fi

# `embassy token create` prints the token on the first line, then a YAML list with its config entry.
create() {
  local out
  # shellcheck disable=SC2086  # EMBASSY is a command line
  out=$($EMBASSY token create "$@")
  TOKEN=$(head -n1 <<<"$out")
  SHA256=$(sed -n -E "s/^[- ] *sha256: *'?\"?([0-9a-f]{64})'?\"?$/\1/p" <<<"$out")
  EXPIRES_AT=$(sed -n -E "s/^[- ] *expires_at: *'?\"?([^'\"]+)'?\"?$/\1/p" <<<"$out")
  [[ $TOKEN =~ ^att_[A-Za-z0-9_-]{43}$ ]] || { echo "gen-env: unexpected token from: $EMBASSY token create $*" >&2; exit 1; }
  [[ $SHA256 =~ ^[0-9a-f]{64}$ ]] || { echo "gen-env: no sha256 in the output of: $EMBASSY token create $*" >&2; exit 1; }
  local actual
  if command -v sha256sum >/dev/null; then
    actual=$(printf %s "$TOKEN" | sha256sum | cut -d' ' -f1)
  else
    actual=$(printf %s "$TOKEN" | shasum -a 256 | cut -d' ' -f1)
  fi
  [[ $actual == "$SHA256" ]] || { echo "gen-env: the printed sha256 is not the token's" >&2; exit 1; }
}

tmp=$(mktemp "${ENV_FILE}.XXXXXX")
trap 'rm -f "$tmp"' EXIT
chmod 0600 "$tmp"
{
  echo "# Generated by deploy/compose/gen-env.sh. Secret: API and join tokens. Delete to rotate."
  echo "ATTACHE_NAMESPACE=$NAMESPACE"
  create --name compose-admin --role admin --payloads
  echo "ATTACHE_ADMIN_TOKEN=$TOKEN"
  echo "ATTACHE_ADMIN_TOKEN_SHA256=$SHA256"
  admin=$TOKEN
  for svc in $SERVICES; do
    create --name "compose-$svc" --join --namespace "$NAMESPACE" --services "$svc" --expires-in "$JOIN_TOKEN_TTL"
    [[ -n $EXPIRES_AT ]] || { echo "gen-env: no expires_at for $svc" >&2; exit 1; }
    var=ATTACHE_JOIN_TOKEN_$(tr '[:lower:]-' '[:upper:]_' <<<"$svc")
    echo "$var=$TOKEN"
    echo "${var}_SHA256=$SHA256"
    echo "${var}_EXPIRES_AT=$EXPIRES_AT"
  done
} >"$tmp"
mv "$tmp" "$ENV_FILE"
trap - EXIT

echo "wrote $ENV_FILE (mode 0600)"
echo "admin token for the console at http://localhost:8080 (shown once; also in $ENV_FILE):"
echo "  $admin"
